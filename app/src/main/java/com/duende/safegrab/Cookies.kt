package com.duende.safegrab

import android.net.Uri
import android.webkit.CookieManager
import android.webkit.WebStorage

object Cookies {

    /** Extrae el host limpio de una URL (ej. "x.com", "instagram.com", "youtube.com", "tiktok.com").
     *  Unifica twitter.com/x.com y agrupa todos los dominios de TikTok.
     */
    fun hostOf(urlStr: String): String? {
        return runCatching {
            var host = Uri.parse(urlStr).host?.lowercase() ?: return@runCatching null
            if (host.startsWith("www.")) host = host.substring(4)
            if (host.startsWith("m.")) host = host.substring(2)
            if (host.startsWith("mobile.")) host = host.substring(7)

            if (host == "twitter.com" || host == "x.com") {
                return "x.com"
            }
            if (host == "fb.watch") {
                return "facebook.com"
            }
            if (host.endsWith("tiktok.com")) {
                return "tiktok.com"
            }
            host
        }.getOrNull()
    }

    /** Devuelve la URL base de inicio de sesión para el WebView temporal según el host. */
    fun loginUrl(host: String): String = when (host) {
        "x.com", "twitter.com" -> "https://x.com/i/flow/login"
        "instagram.com" -> "https://www.instagram.com/accounts/login/"
        "facebook.com" -> "https://www.facebook.com/login"
        "youtube.com" -> "https://accounts.google.com"
        "tiktok.com" -> "https://www.tiktok.com/login"
        else -> "https://$host/"
    }

    /** Convierte el string de cookies del CookieManager a formato Netscape (requerido por yt-dlp). */
    fun toNetscape(host: String, cookieString: String): String = buildString {
        appendLine("# Netscape HTTP Cookie File")
        appendLine("# This file was generated by SafeGrab\n")

        val targetDomain = if (host.startsWith(".")) host else ".$host"
        val cookies = cookieString.split(";")
        for (cookie in cookies) {
            val parts = cookie.trim().split("=", limit = 2)
            if (parts.size == 2) {
                val name = parts[0].trim()
                val value = parts[1].trim()
                if (name.isNotEmpty()) {
                    appendLine("$targetDomain\tTRUE\t/\tTRUE\t2147483647\t$name\t$value")
                    // Si es x.com, duplicar en .twitter.com para redirecciones antiguas
                    if (host == "x.com") {
                        appendLine(".twitter.com\tTRUE\t/\tTRUE\t2147483647\t$name\t$value")
                    }
                }
            }
        }
    }

    /** Borra TODO rastro de sesión del WebView (modo incógnito). */
    fun wipeWebView() {
        val cm = CookieManager.getInstance()
        cm.removeAllCookies(null)
        cm.flush()
        WebStorage.getInstance().deleteAllData()
    }
}
